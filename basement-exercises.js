  let fullDbPromise = null;
  let fullDbCache = null;

  function fetchFullDb() {
    if (fullDbCache) return Promise.resolve(fullDbCache);
    if (!fullDbPromise) {
      fullDbPromise = fetch(FULL_DB_URL)
        .then((r) => (r.ok ? r.json() : []))
        .then((list) => {
          fullDbCache = Array.isArray(list) ? list : [];
          return fullDbCache;
        })
        .catch(() => []);
    }
    return fullDbPromise;
  }

  function normalizeText(s) {
    return String(s || '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, ' ')
      .trim();
  }

  function findBestDbMatch(name, preferredEquipment) {
    if (!fullDbCache || !fullDbCache.length) return null;
    const target = normalizeText(name);
    const words = target.split(' ').filter((w) => w.length > 2);
    let best = null;
    let bestScore = -1;

    for (const item of fullDbCache) {
      const itemName = normalizeText(item.name);
      if (itemName === target) return item;
      let score = 0;
      for (const w of words) {
        if (itemName.includes(w)) score += 3;
      }
      if (preferredEquipment && item.equipment && normalizeText(item.equipment).includes(normalizeText(preferredEquipment))) {
        score += 2;
      }
      if (score > bestScore) {
        bestScore = score;
        best = item;
      }
    }
    return bestScore >= 3 ? best : null;
  }

  function mergeIntoLiftDb(existingMap) {
    const out = { ...(existingMap || {}) };
    for (const ex of BASE_EXERCISES) {
      if (!out[ex.name]) {
        out[ex.name] = { ...ex };
      }
    }
    return out;
  }

  function mergeIntoPhotoMap(existingMap) {
    const out = { ...(existingMap || {}) };
    for (const ex of BASE_EXERCISES) {
      if (!out[ex.name]) {
        out[ex.name] = { slug: ex.slug, customPhotoTop: ex.customPhotoTop, customPhotoBottom: ex.customPhotoBottom };
      }
    }
    return out;
  }

  function mergeIntoCatalogArray(existingArr) {
    const out = Array.isArray(existingArr) ? [...existingArr] : [];
    const seen = new Set(out.map((e) => e.name.toLowerCase()));
    for (const ex of BASE_EXERCISES) {
      if (!seen.has(ex.name.toLowerCase())) {
        out.push({ ...ex });
        seen.add(ex.name.toLowerCase());
      }
    }
    return out;
  }

  // Resolve any exercise name (seeded or newly recommended by AI Pro Trainer).
  // If not in BASE_EXERCISES or basement_custom_catalog, fetches from free-exercise-db and persists it.
  async function resolveExerciseAsync(name, preferredEquipment) {
    const clean = String(name || '').trim();
    if (!clean) return null;
    const seeded = BASE_EXERCISES.find((e) => e.name.toLowerCase() === clean.toLowerCase());
    if (seeded) return seeded;

    let custom = [];
    try {
      custom = JSON.parse(localStorage.getItem('basement_custom_catalog') || '[]');
    } catch (e) {
      custom = [];
    }
    const existingCustom = custom.find((e) => e.name && e.name.toLowerCase() === clean.toLowerCase());
    if (existingCustom) return existingCustom;

    await fetchFullDb();
    const match = findBestDbMatch(clean, preferredEquipment);
    const slug = match?.id || 'Goblet_Squat';
    const eqRaw = (match?.equipment || preferredEquipment || 'Dumbbell').toLowerCase();
    const eq = eqRaw.includes('band') ? 'Band' : eqRaw.includes('body') ? 'Bodyweight' : 'Dumbbell';
    const muscles = [...(match?.primaryMuscles || []), ...(match?.secondaryMuscles || [])].slice(0, 3).join(', ') || 'Full-Body Stabilizers';
    const steps = Array.isArray(match?.instructions) && match.instructions.length
      ? match.instructions.map((s, i) => `${i + 1}. ${s}`).join('\n')
      : `1. Set balanced posture for ${clean}.\n2. Perform controlled reps with 2-3s lowering.`;

    const newEntry = {
      name: clean,
      slug,
      category: 'Core',
      equipment: eq,
      weight: eq === 'Dumbbell' ? 25 : 0,
      reps: 12,
      muscles,
      topCue: `Setup for ${clean} (${eq}).`,
      bottomCue: `Peak contraction on ${clean}.`,
      quickCue: `Control tempo and keep joints aligned on ${clean}.`,
      cue: steps,
      trap: `• Rushing reps or losing brace during ${clean}.`,
      science: `Auto-mapped from free-exercise-db (${slug}) for ${muscles}.`,
      isCustom: true
    };

    try {
      custom.push(newEntry);
      localStorage.setItem('basement_custom_catalog', JSON.stringify(custom));
    } catch (e) {}
    return newEntry;
  }

